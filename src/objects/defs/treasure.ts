function coin(x: number, y: number, z = 0): ObjectPart {
  return round(x, y, 0.045, z, 0.8, GOLD, GOLD_TOP)
}

/** A stack of `n` coins. */
function coinStack(x: number, y: number, n: number): ObjectPart {
  return round(x, y, 0.05, 0, n * 0.9, '#c9a43e', GOLD_TOP)
}

/** A chest body, lid and straps; `x0`..`x1` across, `y0`..`y1` deep. */
function chest(
  x0: number,
  y0: number,
  x1: number,
  y1: number,
  body: string,
  bodyTop: string,
  lid: string,
  lidTop: string,
  trim: string,
  height = 10,
): ObjectPart[] {
  const w = x1 - x0
  const d = y1 - y0
  return [
    box(x0, y0, w, d, 0, height, body, bodyTop),
    box(x0, y0, w, d, height, 4, lid, lidTop),
    box(x0 + w * 0.18, y0 - 0.01, 0.05, d + 0.02, 0, height + 4.4, trim),
    box(x1 - w * 0.18 - 0.05, y0 - 0.01, 0.05, d + 0.02, 0, height + 4.4, trim),
    box(x0 + w / 2 - 0.04, y1, 0.08, 0.025, height - 3, 5, trim),
  ]
}

