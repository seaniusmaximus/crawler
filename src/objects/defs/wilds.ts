/** A ring of `n` points `reach` cells from (x, y), turned by `turn` radians. */
function ring(n: number, x: number, y: number, reach: number, turn = 0): { x: number; y: number }[] {
  return Array.from({ length: n }, (_, i) => {
    const angle = (i / n) * Math.PI * 2 + turn
    return { x: x + Math.cos(angle) * reach, y: y + Math.sin(angle) * reach }
  })
}

/** A snowy pine: stacked cones, snow on each tier's top. */
function pine(x: number, y: number, size: number): ObjectPart[] {
  return [
    round(x, y, 0.05 * size, 0, 6 * size, OAK_DARK),
    round(x, y, 0.4 * size, 6 * size, 12 * size, PINE, SNOW_TOP, 0.18 * size),
    round(x, y, 0.3 * size, 16 * size, 11 * size, PINE, SNOW_TOP, 0.12 * size),
    cone(x, y, 0.2 * size, 25 * size, 12 * size, PINE_TOP),
    cone(x, y, 0.06 * size, 35 * size, 3 * size, SNOW_TOP),
  ]
}

