/** A skull facing +y, `r` cells across, resting on `z`. */
export function skull(x: number, y: number, z: number, r = 0.07): ObjectPart[] {
  const h = r * 45
  return [
    round(x, y, r * 0.85, z, h * 0.35, BONE, BONE_TOP, r),
    round(x, y, r, z + h * 0.35, h * 0.65, BONE, BONE_TOP, r * 0.7),
    box(x - r * 0.55, y + r * 0.82, r * 0.4, 0.01, z + h * 0.45, h * 0.28, '#2a2520'),
    box(x + r * 0.15, y + r * 0.82, r * 0.4, 0.01, z + h * 0.45, h * 0.28, '#2a2520'),
  ]
}

/** A clay pot `r` cells across and `h` tall, with soil showing on top. */
function pot(x: number, y: number, r: number, h: number): ObjectPart[] {
  return [round(x, y, r * 0.75, 0, h, CLAY, '#3a2a1c', r), round(x, y, r * 1.05, h, 1.5, CLAY, '#3a2a1c')]
}

